-- Settlement Amazon: порог времени загрузки — под недельный цикл отчётов (11.10.2026).
--
-- loaded_at у raw_amazon_settlements сдвигается ТОЛЬКО когда приходит новый отчёт: загрузчик идёт каждый день
-- (08:30 Kyiv), но в дни без новых отчётов пишет «new 0» и строк не трогает. Отчёты Amazon закрывает раз в две
-- недели по группе рынков, группы чередуются: ES/DE/FR/IT (загружены 18.09, 02.10), BE/GB (25.09, 09.10) — то есть
-- новые строки приходят раз в неделю. Порог 30 ч загорался каждую неделю на живом загрузчике: инциденты 16.09,
-- 24.09, 01.10, 08.10, 11.10 — тот же класс ложной тревоги, что с возмещениями FBA 10.10.
--
-- 192 ч = неделя между загрузками плюс сутки запаса. Живость самой джобы проверяет job_health_rules (30 ч от
-- последнего успешного прогона), пропущенный двухнедельный цикл группы — порог содержимого (posted_date, 504 ч).
UPDATE kabinet_data.data_freshness_rules
   SET max_age_hours = 192,
       comment = 'Settlement V2 по всем рынкам, загрузчик Kabinet - Settlements Loader, ежедневно; новые строки приходят '
                 'раз в неделю (группы рынков ES/DE/FR/IT и BE/GB закрываются раз в две недели по очереди), поэтому '
                 'синк 192 ч. Живость джобы — job_health_rules (30 ч). Возраст последней проводки в норме 2–16 дней, '
                 'порог 21 день ловит пропущенный цикл.',
       updated_at = now()
 WHERE table_name = 'kabinet_data.raw_amazon_settlements';
