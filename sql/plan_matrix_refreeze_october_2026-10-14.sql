-- Plan Matrix: разовая перезаморозка октября 2026 (выполнять после мержа PR, ДО первого прогона нового ноутбука).
--
-- Октябрь заморожен 14.10 расчётом «на 15.09», когда истории Listings Items ещё не было: у Amazon с продажами меньше
-- 3 штук цена бралась из отчёта листингов, а он отдаёт только обычную цену. 84515000 ES получил 169,95 €, хотя 03.09–30.09
-- шла скидка 129,99 € — её расписание видно в снимке Listings Items за 14.10. Ноутбук теперь применяет такое расписание;
-- чтобы октябрь пересчитался, снимаем его заморозку и расчёт «на 15.09». Следующий прогон посчитает 15.09 заново и
-- заморозит октябрь снова. В таблицу аналитика октябрь ещё не писался — перезаморозка ничего у неё не меняет.
-- Замороженные месяцы прогон не трогает никогда; это ручная правка до первой записи, а не правило.

BEGIN;
DELETE FROM kabinet_data.plan_price_month WHERE month = DATE '2026-10-01';
DELETE FROM kabinet_data.plan_price_daily WHERE calc_date = DATE '2026-09-15';
COMMIT;

SELECT (SELECT count(*) FROM kabinet_data.plan_price_month WHERE month = DATE '2026-10-01') AS october_rows,
       (SELECT count(*) FROM kabinet_data.plan_price_daily WHERE calc_date = DATE '2026-09-15') AS daily_0915_rows;
