-- Уточнение формулировок (25.09.2026): «ФМ …» — наши собственные фирменные магазины, франчайзи —
-- только «Партнер ФМ …», и они за границей. Наш автозаказ партнёрские точки не пополняет, поэтому
-- их остаток нам не нужен вовсе: они просто помечены и исключены из обеспечения и переброски.
UPDATE kabinet_data.warehouses
   SET note = 'Партнёрская точка (франчайзи): товар не наш, в обеспечение каналов и переброску не входит; автозаказ её не пополняет (25.09.2026)'
 WHERE name ILIKE 'Партнер ФМ%';

COMMENT ON COLUMN kabinet_data.warehouse_attributes.is_partner IS
    'Склад партнёра-франчайзи («Партнер ФМ …», за границей): товар не наш, в обеспечение каналов и переброску не входит, автозаказ его не пополняет (решение 25.09.2026). Список читают загрузчики.';
