SELECT t.title AS в_erp,
       COALESCE(n.name_ru, '— НЕТ ПОДПИСИ —') AS по_русски,
       COALESCE(n.name_en, '—') AS по_английски
  FROM kabinet_data.sku_category_tree t
  LEFT JOIN kabinet_data.category_names n ON n.category_key = t.category_key
 WHERE t.depth = 1
 ORDER BY (n.name_ru IS NULL) DESC, t.title;
