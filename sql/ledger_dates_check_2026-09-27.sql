-- Проверка «джоба зелёная, а даты в таблице не прибавляются» и поправка порога возраста
-- остатка FBA, который я сначала задал по неверному наблюдению.
--
-- Что выяснилось разбором 27.09.2026. Джоба Дарины «FBA Inventory Ledger Summary for Tableau»
-- (07:40 Kyiv = 04:40 UTC) запрашивает 1-е число месяца → вчера и пишет ровно то, что вернул
-- Amazon. Отставание не в её коде: в 04:40 UTC Amazon данные за ВЧЕРА ещё не отдаёт, а к 13:00
-- UTC отдаёт полностью — проверено двумя запросами, за один день 26.09 (89 строк) и за её
-- диапазон 01.09–26.09 (2 119 строк против 2 030, которые получил её прогон утром: разница
-- ровно в день 26.09). Поэтому максимальная дата в таблице стабильно отстаёт на двое суток.
--
-- Отсюда порог: 30 часов, который я поставил раньше, был бы ежедневной ложной тревогой. Я
-- вывел его из того, что в `stock_local` даты FBA-снимков шли день в день с прогонами, — а это
-- неверное чтение: снимок за 25.09 записан 27.09, за 24.09 — 26.09, и так все семь дней
-- (`created_at` в `stock_local` показывает это прямо). Нормальное отставание — двое суток,
-- поэтому порог возраста 72 часа: «третьи сутки» — это уже поломка, а не обычный день.
UPDATE kabinet_data.reorder_params
   SET value = '72',
       note = 'Порог возраста остатка FBA в stock_local (проверка сторожа [STOCK_FBA]). '
              'Нормальное отставание источника — двое суток: в 04:40 UTC Amazon данные за вчера '
              'ещё не отдаёт (разбор 27.09.2026), поэтому 30 ч давали ложную тревогу каждый день',
       updated_at = now()
 WHERE key = 'stock_fba_max_age_hours';

-- Допустимое отставание дат в самом источнике. Два дня — это наблюдаемая норма при одном
-- утреннем прогоне; инцидент заводится на третьи сутки, то есть когда даты действительно
-- перестали прибавляться. Если второй прогон дня закрепится и отставание станет одним днём,
-- порог можно опустить до 1 — но уже по замеру, а не заранее.
INSERT INTO kabinet_data.reorder_params (key, value, note)
VALUES ('ledger_summary_max_lag_days', '2',
        'Допустимое отставание MAX(date) в dnipro_m.raw_amazon_fba_inventory_ledger_summary '
        '(проверка сторожа [LEDGER_DATES]: прогон успешен, а даты не прибавляются)')
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, note = EXCLUDED.note, updated_at = now();
