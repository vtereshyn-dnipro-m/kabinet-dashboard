-- Порог возраста остатка FBA в kabinet_data.stock_local — для проверки сторожа «[STOCK_FBA]».
--
-- Почему 30 часов. Ячейка FBA в `Kabinet - Stock Loader` пишет `snapshot_date = date` из отчёта
-- Дарины, и до 25.09.2026 эта дата совпадала с днём прогона: 22, 23, 24, 25 сентября — по строке
-- на день. То есть нормальное отставание нулевое, и снимок «вчерашний» (24 ч) ещё в пределах
-- нормы, а «позавчерашний» (48 ч) — уже поломка. Загрузчик идёт в 12:00 и 15:00 Kyiv, поэтому
-- 30 часов дают запас на сдвиг прогона и не пропускают пропущенный день.
--
-- Возраст считается по СОДЕРЖИМОМУ (`snapshot_date`), а не по времени записи: строку сегодня
-- можно записать и с данными за прошлую неделю — именно это и случилось 26–27.09.
INSERT INTO kabinet_data.reorder_params (key, value, note)
VALUES ('stock_fba_max_age_hours', '30',
        'Порог возраста остатка FBA в stock_local (проверка сторожа [STOCK_FBA]); '
        'нормальное отставание источника — ноль дней, поэтому 30 ч = пропущенный день')
ON CONFLICT (key) DO UPDATE SET value = EXCLUDED.value, note = EXCLUDED.note, updated_at = now();
