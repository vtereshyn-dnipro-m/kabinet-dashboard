-- Плечо PL в автозаказе: 16 → 11 дней по фактическим поставкам, а не по оценке.
--
-- Шестнадцать собирались как 8 (маршрут Piasecznie → Мадрид) + 5 (ожидание среды) + 3 (Мадрид → FBA).
-- Замер по 92 принятым заказам Odoo за 2026 (польское юрлицо → склад «RS Spain Madrid (Stock)»,
-- без FBA, без KULGA, без магазинов, отменённые отсеяны) даёт срок «заказ → приёмка в Мадриде»:
-- медиана 7 дней, p25 5, p75 8, максимум 19; дольше 13 дней — 9 поставок из 92.
--
-- Ключевое: эти 7 дней УЖЕ включают ожидание рейса. Заказы ставят в разные дни недели, и если бы
-- к восьми дням транзита сверху ложилось пять дней ожидания, медиана была бы 11–13, а не 7 при
-- p75 = 8. Подтверждение с другой стороны: обещанная перевозчиком дата (`date_planned`) — тоже
-- медиана 7 дней от заказа, то есть обещание совпадает с фактом. Значит ожидание считалось дважды.
--
-- Маршрут оставляем 8 дней (факт 7, день запаса оправдан разбросом до 19), а ожидание обнуляем:
-- плечо PL становится 8 + 0 + 3 = 11. Не удаляем параметр, а ставим ноль с пояснением — иначе
-- следующий человек увидит пропажу и вернёт пятёрку «как было».
UPDATE kabinet_data.reorder_params
   SET value = '0',
       note = 'Ожидание рейса в Мадрид. Ноль с 27.09.2026: замер 92 поставок Odoo за 2026 показал '
              'срок «заказ → приёмка» медиана 7 дн, и ожидание уже внутри него — прибавлять его '
              'к маршруту значит считать дважды. Плечо PL = 8 (маршрут) + 0 + 3 (Мадрид → FBA) = 11',
       updated_at = now()
 WHERE key = 'madrid_dispatch_wait_days';
