-- `coverage_react_weeks` = 1 — «плюс одна дополнительная неделя для реакции менеджера» из §102.
-- Считается от РЕАЛИСТИЧНОГО покрытия, а не от первой дыры на FBA: по первой дыре условие ловило
-- 87 строк из 103 (замер 28.09.2026), потому что витрина FBA пустеет, пока мадридский запас
-- закрывает её месяцами. По реалистичному — 20 строк, и все они уже critical.
--
-- `coverage_late_inbound_min_days` = 7 — сколько дней просрочки терпим, прежде чем звать.
-- В день прибытия накладная нормально висит «в пути»: ERP закрывает их не мгновенно.
--
-- `coverage_late_inbound_max_days` = 60 — а вот дальше это уже не логистика. В ERP накладные
-- почти не закрываются вовсе: из 25 938 строк `shipments_history` дату приёмки имеют 181,
-- а «просроченных» ТТН 477 на 116 тыс. штук, и все они — в магазины и партнёрам, к нам
-- ни одной. Без верхней границы алерт превратился бы в ежедневный список вечных хвостов.
