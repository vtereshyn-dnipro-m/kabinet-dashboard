-- Наблюдение за отправкой запросов на отзыв. Lakebase, kabinet_data.
--
-- Почему 41 час простоя прошёл незамеченным: правил два, а метка одна.
--
--   правило «Kabinet - Review Requests (Morning)»     ждёт имя, которого нет
--   правило «Kabinet - Review Requests (ES Evening)»  ждёт имя, которого нет
--   ноутбук пишет метку «Kabinet - Review Requests»   её не ждёт никто
--
-- То есть оба правила слали «no success in N h» каждый день при живой
-- джобе, а настоящую метку не проверял никто. Ложные алерты приучили не
-- читать эти сообщения — и настоящий простой уехал вместе с ними.

BEGIN;

-- ── 1. Правило переводим на имя, которое реально пишется ─────────────
-- job_id оставляем утренний: одна метка — одно правило.
UPDATE kabinet_data.job_health_rules
   SET job_name = 'Kabinet - Review Requests',
       schedule_description = '09:00 Kyiv + 19:00 Madrid daily',
       note = 'Оба слота пишут одну метку «Kabinet - Review Requests», '
              'поэтому правило одно. Порог 26 ч: за 60 дней наибольший '
              'разрыв между прогонами 24 ч, обычный ночной 13 ч. Чтобы '
              'различать утро и вечер, ноутбук должен писать две разные '
              'метки — тогда и правила станут двумя.'
 WHERE job_id = 504383462189415;

-- ── 2. Второе правило выключаем, но НЕ удаляем ───────────────────────
-- В нём лежит job_id вечерней джобы, а взять его больше неоткуда:
-- Jobs API сервис-принципалу закрыт. Удалить — потерять номер.
UPDATE kabinet_data.job_health_rules
   SET is_active = false,
       note = 'Выключено 10.09.2026: обе джобы пишут одну метку, два '
              'правила на неё давали ежедневный ложный алерт. Строку '
              'держим ради job_id вечерней джобы. Включать обратно, '
              'когда ноутбук начнёт писать отдельную метку по слоту.'
 WHERE job_id = 760565204236769;

-- ── 3. Правило свежести на сами данные ───────────────────────────────
-- Отдельный сигнал от пульса, и ломается он иначе: пульс говорит «ячейка
-- доработала до конца», а эта проверка — «строки действительно легли».
--
-- Колонка checked_at, а не sent_at: проверка идёт каждый прогон, а
-- отправка только когда есть подходящие заказы. Пустая отправка — норма,
-- пустая проверка — поломка.
--
-- Порог 26 ч по фактическим разрывам за 60 дней:
--   меньше часа (внутри прогона)   95
--   1–12 ч  (утро → вечер)         23, максимум 11.0
--   12–14 ч (вечер → утро)         22, максимум 13.0
--   14–20 ч                         2, максимум 18.9
--   20–26 ч (пропущен прогон)       8, максимум 24.0
--   больше 26 ч                     0
-- Порог 26 ч молчит на всей наблюдаемой истории и ловит 41 час.
INSERT INTO kabinet_data.data_freshness_rules
       (table_name, date_column, max_age_hours, source_type, owner_role,
        is_active, comment, updated_at)
VALUES ('kabinet_data.review_request_log', 'checked_at', 26,
        'lakebase', 'reviews', true,
        'Запросы на отзыв: два прогона в сутки, 06:02 и 17:03 UTC. Порог 26 ч '
        'подобран по разрывам за 60 дней — наибольший 24 ч, обычный ночной 13 ч. '
        'Смотрим checked_at, а не sent_at: отправка бывает пустой по делу, '
        'проверка — нет.', now())
ON CONFLICT (table_name) DO NOTHING;

COMMIT;

-- ── Проверка ─────────────────────────────────────────────────────────
SELECT r.job_name, r.is_active, r.expected_interval_hours,
       p.last_success_at IS NOT NULL AS metka_est
  FROM kabinet_data.job_health_rules r
  LEFT JOIN kabinet_data.system_pulse p ON p.job_name = r.job_name
 WHERE r.job_id IN (504383462189415, 760565204236769)
 ORDER BY r.job_name;
