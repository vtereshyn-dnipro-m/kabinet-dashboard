# -*- coding: utf-8 -*-
"""Выкладка общего экрана «Доступ» в Listing Suite и сверка побайтно.

Источник один — `access_screen.py` в этом репозитории. В Listing Suite лежит его копия,
и она обязана совпадать байт в байт: иначе появятся две версии одной админки, которые
разойдутся молча — таблицы-то общие, а поведение разное.

Скрипт делает три вещи:
  1) собирает в сам файл словарь `ТЕКСТЫ` из `i18n` Кабинета — только те ключи, которые
     экран действительно зовёт. Чужому хозяину они нужны (своих у него нет), а писать
     их там руками значило бы завести вторую копию фраз;
  2) кладёт файл в Listing Suite, дописав в шапку sha256 содержимого — по нему тест на
     той стороне ловит правку копии на месте;
  3) сверяет обе стороны и говорит, что сделал.

Запуск: python scratchpad/sync_access_screen.py [--проверить]
  --проверить — ничего не писать, только сказать, совпадают ли копии (для прогона
  перед коммитом).
"""
import ast
import hashlib
import pathlib
import re
import sys

КОРЕНЬ = pathlib.Path(__file__).resolve().parent.parent
ИСТОЧНИК = КОРЕНЬ / "access_screen.py"
import os

КОРЕНЬ_LS = pathlib.Path(os.environ.get(
    "LISTING_SUITE_ROOT", "/Users/vitter/Documents/Code/listing-analyzer-dashboard"))
ЦЕЛЬ = КОРЕНЬ_LS / "access_screen.py"
ЯЗЫКИ = ("ru", "uk", "en")


def ключи_экрана(текст: str) -> list:
    """Ключи, которые экран зовёт литералом: `t("…")`. Склейки вида `t("x." + y)`
    сюда не попадают намеренно — их собирают из частей, и собрать список заранее
    нельзя; такие ключи обязаны быть у хозяина в словаре."""
    прямые = set(re.findall(r'\bt\(\s*"([\w.]+)"', текст))
    # f-строки вида t(f"auth.admin.mode_{_m}") — добираем известные хвосты руками:
    # их немного, и каждый тут назван, чтобы пропажа была видна глазами
    прямые |= {f"auth.admin.mode_{n}" for n in (0, 1, 2)}
    прямые |= {f"auth.role.{r}" for r in
               ("viewer", "country_manager", "demand_planner", "admin",
                "content_manager", "approver")}
    прямые |= {f"auth.admin.sec.{s}" for s in
               ("forecast", "dictionaries", "ads", "reorder", "incidents", "access",
                "other", "ls_content", "ls_amazon", "ls_method", "ls_settings",
                "ls_page")}
    прямые |= {f"auth.admin.res.{r}" for r in
               ("ok", "first_login", "denied_domain", "denied_disabled", "logout")}
    прямые |= {"auth.log.who.система", "auth.log.who.kabinet-app",
               "auth.log.who.watchdog", "auth.log.who.qa-агент"}
    # Ключи, собираемые склейкой (`t("auth.action." + действие)`), заранее не
    # перечислить — берём ЦЕЛИКОМ две семьи: названия прав и фразы журнала. Это и есть
    # вокабуляр матрицы и журнала, и неполный он будет виден сырым ключом на экране.
    прямые = {к for к in прямые if not к.endswith(".")}
    return sorted(прямые)


СЕМЬИ = ("auth.action.", "auth.log.act.")


def словарь_кабинета() -> dict:
    """`TRANSLATIONS` из i18n Кабинета — разбором дерева, без импорта: тащить за собой
    streamlit ради чтения словаря незачем."""
    дерево = ast.parse((КОРЕНЬ / "i18n.py").read_text(encoding="utf-8"))
    for узел in дерево.body:
        цель = (узел.targets[0] if isinstance(узел, ast.Assign)
                else getattr(узел, "target", None))
        if getattr(цель, "id", "") == "TRANSLATIONS":
            return ast.literal_eval(узел.value)
    raise SystemExit("в i18n.py не нашёлся TRANSLATIONS")


def собрать_тексты(текст: str) -> tuple:
    словарь = словарь_кабинета()
    нужные = ключи_экрана(текст)
    нужные += sorted(к for к in словарь
                     if any(к.startswith(сем) for сем in СЕМЬИ) and к not in нужные)
    собрано = {я: {} for я in ЯЗЫКИ}
    нет = []
    for ключ in нужные:
        if ключ not in словарь:
            нет.append(ключ)
            continue
        for я in ЯЗЫКИ:
            значение = словарь[ключ].get(я)
            if значение is not None:
                собрано[я][ключ] = значение
    строки = ["ТЕКСТЫ = {"]
    for я in ЯЗЫКИ:
        строки.append(f'    "{я}": {{')
        for ключ in sorted(собрано[я]):
            значение = собрано[я][ключ].replace("\\", "\\\\").replace('"', '\\"')
            значение = значение.replace("\n", "\\n")
            строки.append(f'        "{ключ}": "{значение}",')
        строки.append("    },")
    строки.append("}")
    return "\n".join(строки), нет, len(нужные)


def вставить(текст: str, блок: str) -> str:
    начало = "# НАЧАЛО ТЕКСТОВ (не править руками)\n"
    конец = "\n# КОНЕЦ ТЕКСТОВ"
    i, j = текст.index(начало) + len(начало), текст.index(конец)
    return текст[:i] + блок + текст[j:]


def с_отпечатком(текст: str) -> str:
    """Дописать в шапку sha256 СОДЕРЖИМОГО (без самой строки отпечатка): по нему копия
    ловит правку себя на месте. Строка одна и первая — её видно сразу."""
    тело = re.sub(r"^# ОТПЕЧАТОК ИСТОЧНИКА: [0-9a-f]{64}\n", "", текст, flags=re.M)
    отпечаток = hashlib.sha256(тело.encode("utf-8")).hexdigest()
    return f"# ОТПЕЧАТОК ИСТОЧНИКА: {отпечаток}\n" + тело


def тело_без_отпечатка(текст: str) -> str:
    return re.sub(r"^# ОТПЕЧАТОК ИСТОЧНИКА: [0-9a-f]{64}\n", "", текст, flags=re.M)


def проверить() -> list:
    """Список бед или пустой список. Зовётся и руками, и обязательными прогонами.

    Отсутствие копии — тоже беда, а не «нечего проверять»: иначе гарантия «один экран
    на два приложения» держалась бы на том, что чей-то рабочий стол устроен как мой.
    Путь к Listing Suite можно задать переменной `LISTING_SUITE_ROOT`, и в сообщении
    это написано — проверка обязана говорить, как её выполнить, а не только падать."""
    беда = []
    источник = ИСТОЧНИК.read_text(encoding="utf-8")
    блок, нет_перевода, _ = собрать_тексты(источник)
    должно_быть = с_отпечатком(вставить(источник, блок))

    # 1) источник правили, а выкладку не делали: отпечаток или тексты отстали
    if тело_без_отпечатка(источник) != тело_без_отпечатка(должно_быть):
        беда.append("источник изменён без выкладки — прогнать "
                    "scratchpad/sync_access_screen.py")
    м = re.match(r"# ОТПЕЧАТОК ИСТОЧНИКА: ([0-9a-f]{64})\n", источник)
    if not м:
        беда.append("у источника нет отпечатка в первой строке")
    elif hashlib.sha256(тело_без_отпечатка(источник).encode("utf-8")).hexdigest() != м.group(1):
        беда.append("отпечаток источника не совпадает с его содержимым")

    # 2) копия на той стороне
    if not ЦЕЛЬ.exists():
        беда.append(f"копии нет: {ЦЕЛЬ}. Путь задаётся LISTING_SUITE_ROOT")
    elif ЦЕЛЬ.read_bytes() != ИСТОЧНИК.read_bytes():
        беда.append("копия и источник РАЗОШЛИСЬ — выложить заново")

    if нет_перевода:
        беда.append(f"нет перевода у ключей: {', '.join(нет_перевода)}")
    return беда


def выложить() -> int:
    источник = ИСТОЧНИК.read_text(encoding="utf-8")
    блок, нет_перевода, всего = собрать_тексты(источник)
    новый = с_отпечатком(вставить(источник, блок))
    ИСТОЧНИК.write_text(новый, encoding="utf-8")
    ЦЕЛЬ.write_text(новый, encoding="utf-8")
    одинаково = ИСТОЧНИК.read_bytes() == ЦЕЛЬ.read_bytes()
    print(f"ключей экрана: {всего}, без перевода: {нет_перевода or 'нет'}")
    print(f"выложено в {ЦЕЛЬ}")
    print("побайтно совпадает:", одинаково)
    return 0 if одинаково and not нет_перевода else 1


# ВСЁ, что пишет файлы, живёт под этим условием. Проверку зовут ИМПОРТОМ (её встроил в
# себе обязательный прогон `smoke_full.py`), и первая версия на импорте делала выкладку:
# проверка молча приводила копию к источнику и потом сообщала, что они совпадают. Это
# хуже отсутствующей проверки — она не падает никогда.
if __name__ == "__main__":
    if "--проверить" in sys.argv:
        беда = проверить()
        for b in беда:
            print("  ПРОВАЛ", b)
        print("итог:", "совпадают" if not беда else f"бед {len(беда)}")
        sys.exit(1 if беда else 0)
    sys.exit(выложить())
